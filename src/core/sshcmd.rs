//! Build argument vectors for the system ssh tools (section 7.1).
//!
//! Every call goes through a generated ssh config passed with `-F`, so per-hop keys,
//! users and ports work for jump chains.

use crate::core::error::Result;
use crate::core::fsutil::{private_dir, write_atomic};
use crate::core::model::{Config, Forward, Server};
use crate::core::paths::Paths;
use crate::core::resolve;
use std::path::{Path, PathBuf};

/// Prefix for host aliases in the generated config.
pub const ALIAS_PREFIX: &str = "shhoba.";

pub fn alias(name: &str) -> String {
    format!("{ALIAS_PREFIX}{name}")
}

/// What every builder needs: the ssh binary and the generated config file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SshCtx {
    pub ssh_bin: String,
    pub config_file: PathBuf,
}

impl SshCtx {
    fn base(&self) -> Vec<String> {
        vec![
            self.ssh_bin.clone(),
            "-F".into(),
            self.config_file.display().to_string(),
        ]
    }
}

/// Quote a value for an ssh_config line if it needs it.
fn cfg_value(v: &str) -> String {
    if v.is_empty() || v.chars().any(|c| c.is_whitespace() || c == '"' || c == '#') {
        format!("\"{}\"", v.replace('"', ""))
    } else {
        v.to_string()
    }
}

/// Options for rendering the config.
pub struct RenderOpts<'a> {
    /// Alias prefix: `shhoba.` for internal use, empty for `export ssh-config`.
    pub prefix: &'a str,
    /// ControlMaster socket directory, or None to omit the ControlMaster block.
    pub control_dir: Option<&'a Path>,
    /// Append `Include` lines that restore the user's and system config (needed with -F).
    pub include_defaults: bool,
}

/// Render the ssh config text for every server.
pub fn render_ssh_config(cfg: &Config, opts: &RenderOpts) -> String {
    let mut out = String::from("# Generated by shhoba. Do not edit.\n");
    for s in &cfg.server {
        out.push_str(&format!("\nHost {}{}\n", opts.prefix, s.name));
        out.push_str(&format!("    HostName {}\n", cfg_value(&s.host)));
        if let Some(u) = &s.user {
            out.push_str(&format!("    User {}\n", cfg_value(u)));
        }
        if let Some(p) = s.port {
            out.push_str(&format!("    Port {p}\n"));
        }
        if let Some(k) = &s.key {
            out.push_str(&format!(
                "    IdentityFile {}\n    IdentitiesOnly yes\n",
                cfg_value(&k.display().to_string())
            ));
        }
        if !s.jump.is_empty() {
            let hops: Vec<String> = s
                .jump
                .iter()
                .map(|j| format!("{}{j}", opts.prefix))
                .collect();
            out.push_str(&format!("    ProxyJump {}\n", hops.join(",")));
        }
    }
    if let Some(dir) = opts.control_dir {
        let path = dir.display().to_string().replace('%', "%%");
        out.push_str(&format!(
            "\nHost {}*\n    ControlMaster auto\n    ControlPath {}\n    ControlPersist 10m\n",
            opts.prefix,
            cfg_value(&format!("{path}/%C"))
        ));
    }
    if opts.include_defaults {
        out.push_str("\nHost *\nInclude ~/.ssh/config\nInclude /etc/ssh/ssh_config\n");
    }
    out
}

/// Regenerate `<state>/ssh_config` if its content changed and return the context for
/// building commands.
pub fn ensure_ssh_config(cfg: &Config, paths: &Paths) -> Result<SshCtx> {
    private_dir(&paths.state_dir)?;
    let ctl = paths.ctl_dir();
    if cfg.settings.control_master {
        private_dir(&ctl)?;
    }
    let text = render_ssh_config(
        cfg,
        &RenderOpts {
            prefix: ALIAS_PREFIX,
            control_dir: cfg.settings.control_master.then_some(ctl.as_path()),
            include_defaults: true,
        },
    );
    let file = paths.ssh_config();
    if std::fs::read_to_string(&file).ok().as_deref() != Some(text.as_str()) {
        write_atomic(&file, text.as_bytes(), 0o600, false)?;
    }
    Ok(SshCtx {
        ssh_bin: cfg.settings.ssh_bin.clone(),
        config_file: file,
    })
}

/// Interactive session, optionally with forwards added.
pub fn ssh_connect(ctx: &SshCtx, server: &Server, forwards: &[&Forward]) -> Vec<String> {
    let mut v = ctx.base();
    v.extend(server.extra_args.iter().cloned());
    for f in forwards {
        v.extend(f.args());
    }
    v.push(alias(&server.name));
    v
}

/// Background tunnel for one forward (section 7.4).
pub fn ssh_tunnel(ctx: &SshCtx, server: &Server, fwd: &Forward) -> Vec<String> {
    let mut v = ctx.base();
    v.push("-N".into());
    for o in [
        "ExitOnForwardFailure=yes",
        "ServerAliveInterval=30",
        "ServerAliveCountMax=3",
        "BatchMode=yes",
        "ControlPath=none",
    ] {
        v.push("-o".into());
        v.push(o.into());
    }
    v.extend(server.extra_args.iter().cloned());
    v.extend(fwd.args());
    v.push(alias(&server.name));
    v
}

/// Reachability check of `server` through its last jump hop: `ssh -W host:port <hop>`.
/// Returns None for servers without jumps.
pub fn ssh_check(ctx: &SshCtx, server: &Server) -> Option<Vec<String>> {
    let hop = server.jump.last()?;
    let mut v = ctx.base();
    for o in ["BatchMode=yes", "ConnectTimeout=5"] {
        v.push("-o".into());
        v.push(o.into());
    }
    let host = if server.host.contains(':') {
        format!("[{}]", server.host)
    } else {
        server.host.clone()
    };
    v.push("-W".into());
    v.push(format!("{host}:{}", server.port_or_default()));
    v.push(alias(hop));
    Some(v)
}

/// Quote one argument for a POSIX shell, leaving common safe strings bare.
pub fn shell_quote(a: &str) -> String {
    let safe = |c: char| c.is_ascii_alphanumeric() || "@%+=:,./_-".contains(c);
    if !a.is_empty() && a.chars().all(safe) {
        a.to_string()
    } else {
        format!("'{}'", a.replace('\'', "'\\''"))
    }
}

/// Shell-quote and join an argv for display or copy-paste.
pub fn shell_join(argv: &[String]) -> String {
    argv.iter()
        .map(|a| shell_quote(a))
        .collect::<Vec<_>>()
        .join(" ")
}

/// A readable, self-contained equivalent command using `-J` (for `show` and the details
/// pane). Per-hop keys cannot be expressed this way; the real command uses `-F`.
pub fn human_command(server: &Server, cfg: &Config) -> String {
    let mut v: Vec<String> = vec!["ssh".into()];
    let hops = resolve::chain(cfg, server).unwrap_or_else(|_| server.jump.clone());
    if !hops.is_empty() {
        let specs: Vec<String> = hops
            .iter()
            .map(|h| {
                cfg.get(h)
                    .map(Server::destination)
                    .unwrap_or_else(|| h.clone())
            })
            .collect();
        v.push("-J".into());
        v.push(specs.join(","));
    }
    if let Some(k) = &server.key {
        v.push("-i".into());
        v.push(shellexpand::tilde(&k.display().to_string()).into_owned());
    }
    if let Some(p) = server.port {
        v.push("-p".into());
        v.push(p.to_string());
    }
    v.extend(server.extra_args.iter().cloned());
    let mut dest = String::new();
    if let Some(u) = &server.user {
        dest.push_str(u);
        dest.push('@');
    }
    dest.push_str(&server.host);
    v.push(dest);
    shell_join(&v)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::config::parse;

    pub(crate) const FIXTURE: &str = r#"
[[server]]
name = "bastion"
host = "203.0.113.10"
user = "ata"
key = "~/.ssh/id_ed25519"

[[server]]
name = "db-prod"
host = "10.0.0.5"
user = "postgres"
port = 2222
jump = ["bastion"]
extra_args = ["-o", "ServerAliveInterval=30"]

  [[server.forward]]
  name = "pg"
  kind = "local"
  bind = "127.0.0.1"
  local_port = 5432
  remote = "localhost:5432"
  auto = true

  [[server.forward]]
  name = "socks"
  kind = "socks"
  local_port = 1080
"#;

    fn ctx() -> SshCtx {
        SshCtx {
            ssh_bin: "ssh".into(),
            config_file: "/state/ssh_config".into(),
        }
    }

    #[test]
    fn generated_config() {
        let cfg = parse(FIXTURE, "t").unwrap();
        let text = render_ssh_config(
            &cfg,
            &RenderOpts {
                prefix: ALIAS_PREFIX,
                control_dir: Some(Path::new("/home/u/.local/state/shhoba/ctl")),
                include_defaults: true,
            },
        );
        insta::assert_snapshot!(text);
    }

    #[test]
    fn exported_config() {
        let cfg = parse(FIXTURE, "t").unwrap();
        let text = render_ssh_config(
            &cfg,
            &RenderOpts {
                prefix: "",
                control_dir: None,
                include_defaults: false,
            },
        );
        insta::assert_snapshot!(text);
    }

    #[test]
    fn argv_builders() {
        let cfg = parse(FIXTURE, "t").unwrap();
        let db = cfg.get("db-prod").unwrap();
        let pg = db.forward("pg").unwrap();
        insta::assert_debug_snapshot!((
            ssh_connect(&ctx(), db, &[]),
            ssh_connect(&ctx(), db, &[pg]),
            ssh_tunnel(&ctx(), db, db.forward("socks").unwrap()),
            ssh_check(&ctx(), db),
            ssh_check(&ctx(), cfg.get("bastion").unwrap()),
        ));
    }

    #[test]
    fn quoting() {
        assert_eq!(shell_quote("a@b:1"), "a@b:1");
        assert_eq!(shell_quote("a b"), "'a b'");
        assert_eq!(shell_quote("it's"), "'it'\\''s'");
        assert_eq!(shell_quote(""), "''");
    }

    #[test]
    fn human() {
        let cfg = parse(FIXTURE, "t").unwrap();
        assert_eq!(
            human_command(cfg.get("db-prod").unwrap(), &cfg),
            "ssh -J ata@203.0.113.10 -p 2222 -o ServerAliveInterval=30 postgres@10.0.0.5"
        );
        assert_eq!(
            human_command(cfg.get("bastion").unwrap(), &cfg),
            format!(
                "ssh -i {} ata@203.0.113.10",
                shellexpand::tilde("~/.ssh/id_ed25519")
            )
        );
    }

    #[test]
    fn writes_only_on_change() {
        let dir = tempfile::tempdir().unwrap();
        let paths = Paths {
            config_dir: dir.path().into(),
            config_file: dir.path().join("servers.toml"),
            state_dir: dir.path().join("state"),
        };
        let cfg = parse(FIXTURE, "t").unwrap();
        let ctx = ensure_ssh_config(&cfg, &paths).unwrap();
        let m1 = std::fs::metadata(&ctx.config_file)
            .unwrap()
            .modified()
            .unwrap();
        std::thread::sleep(std::time::Duration::from_millis(20));
        ensure_ssh_config(&cfg, &paths).unwrap();
        let m2 = std::fs::metadata(&ctx.config_file)
            .unwrap()
            .modified()
            .unwrap();
        assert_eq!(m1, m2);
        use std::os::unix::fs::PermissionsExt;
        let mode = std::fs::metadata(&ctx.config_file)
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600);
        let mode = std::fs::metadata(paths.ctl_dir())
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o700);
    }
}
